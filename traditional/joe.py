"""
traditional/analyse_results.py

CLI error-analysis tool for GTSRB prediction CSVs generated by joe.py.
Automatically adapts figure titles and output folders to the input CSV name(s).

Usage examples (from CompVisCW2/traditional or CompVisCW2 root):
  # Single experiment
  python analyse_results.py linear_svc_lbp_only.csv

  # Compare two experiments (e.g., HOG + LBP vs. Raw HOG baseline)
  python analyse_results.py linear_svc_hog_plus_lbp.csv --compare linear_svc_hog_baseline.csv

  # Custom title override (optional)
  python analyse_results.py linear_svc_hog_plus_lbp.csv --label "LinearSVC (HOG + Spatial LBP)"
"""

import argparse
from pathlib import Path
import cv2
import matplotlib.pyplot as plt
import numpy as np
import pandas as pd
from sklearn.metrics import accuracy_score, f1_score


# ===========================================================================
# CONFIGURATION & PATHS
# ===========================================================================
ROOT_DIR = Path(__file__).resolve().parent.parent
DATA_DIR = ROOT_DIR / "data" / "clean_dataset"
CLASS_CSV = ROOT_DIR / "class.csv"

OUTPUT_DIR = Path(__file__).resolve().parent / "outputs"
PLOTS_DIR = OUTPUT_DIR / "plots"


def resolve_csv_path(csv_arg: str) -> Path:
    """Resolve a CSV path from an exact path or a filename inside traditional/outputs/."""
    candidates = [
        Path(csv_arg),
        OUTPUT_DIR / csv_arg,
        OUTPUT_DIR / f"{csv_arg}.csv",
    ]
    for path in candidates:
        if path.is_file():
            return path.resolve()

    available = sorted(p.name for p in OUTPUT_DIR.glob("*.csv"))
    available_str = "\n  - ".join(available) if available else "(none found)"
    raise FileNotFoundError(
        f"Could not find CSV '{csv_arg}'.\n"
        f"Available CSVs in {OUTPUT_DIR}:\n  - {available_str}"
    )


def format_model_label(stem: str) -> str:
    """Convert a CSV filename stem like 'linear_svc_hog_plus_lbp' into 'LinearSVC (HOG + LBP)'."""
    known_models = {
        "linear_svc": "LinearSVC",
        "random_forest": "RandomForest",
    }
    token_map = {
        "hog": "HOG",
        "lbp": "LBP",
        "hsv": "HSV",
        "clahe": "CLAHE",
        "pca": "PCA",
        "plus": "+",
        "only": "Only",
        "baseline": "Baseline",
        "raw": "Raw",
    }

    model_prefix = None
    remainder = stem
    for prefix, pretty in known_models.items():
        if stem.startswith(prefix):
            model_prefix = pretty
            remainder = stem[len(prefix):].lstrip("_")
            break

    tokens = [token_map.get(t.lower(), t.capitalize()) for t in remainder.split("_") if t]
    exp_text = " ".join(tokens)

    if model_prefix and exp_text:
        return f"{model_prefix} ({exp_text})"
    if model_prefix:
        return model_prefix
    return exp_text or stem


def load_class_names(csv_path: Path) -> dict[int, str]:
    """Map integer ClassId to human-readable SignName from class.csv."""
    df = pd.read_csv(csv_path)
    return dict(zip(df["ClassId"], df["SignName"]))


def short_label(class_id: int, class_names: dict[int, str], max_len: int = 24) -> str:
    """Return a concise 'ID: SignName' string that fits cleanly on plots."""
    name = class_names.get(class_id, f"Class {class_id}")
    if len(name) > max_len:
        name = name[: max_len - 3] + "..."
    return f"{class_id}: {name}"


# ===========================================================================
# 1. TOP CONFUSION PAIRS (HORIZONTAL BAR CHART)
# ===========================================================================
def plot_top_confusions(
    df: pd.DataFrame,
    class_names: dict[int, str],
    model_label: str,
    save_path: Path,
    top_n: int = 15,
) -> None:
    errors = df[df["true_label"] != df["pred_label"]]
    if errors.empty:
        print(f"No misclassifications found for {model_label}; skipping top confusions plot.")
        return

    pair_counts = (
        errors.groupby(["true_label", "pred_label"])
        .size()
        .reset_index(name="count")
        .sort_values("count", ascending=False)
        .head(top_n)
    )

    labels = [
        f"{short_label(r.true_label, class_names, 24)}  →  {short_label(r.pred_label, class_names, 24)}"
        for r in pair_counts.itertuples(index=False)
    ]
    counts = pair_counts["count"].values

    fig, ax = plt.subplots(figsize=(11.5, 6.5))
    bars = ax.barh(labels[::-1], counts[::-1], color="#d9534f", edgecolor="black", alpha=0.85)
    ax.set_xlabel("Number of Misclassifications", fontsize=11)
    ax.set_xlim(0, max(counts) * 1.12)
    ax.set_title(f"Top {len(pair_counts)} Confusion Pairs — {model_label}", fontsize=13, fontweight="bold")
    ax.grid(axis="x", linestyle="--", alpha=0.5)

    for bar in bars:
        width = bar.get_width()
        ax.text(width + max(counts) * 0.015, bar.get_y() + bar.get_height() / 2, f"{int(width)}", va="center", fontsize=9)

    plt.tight_layout()
    plt.savefig(save_path, dpi=300, bbox_inches="tight")
    plt.close()
    print(f"Saved: {save_path}")


# ===========================================================================
# 2. VISUAL FAILURE GRID (CONTACT SHEET)
# ===========================================================================
def plot_failure_grid(
    df: pd.DataFrame,
    class_names: dict[int, str],
    model_label: str,
    save_path: Path,
    n_samples: int = 16,
    seed: int = 42,
) -> None:
    errors = df[df["true_label"] != df["pred_label"]]
    if errors.empty:
        print(f"No misclassifications found for {model_label}; skipping failure grid.")
        return

    sample = errors.sample(n=min(n_samples, len(errors)), random_state=seed)

    cols = 4
    rows = int(np.ceil(len(sample) / cols))
    fig, axes = plt.subplots(rows, cols, figsize=(12, 3.2 * rows))
    axes = np.atleast_1d(axes).flatten()

    for ax, row in zip(axes, sample.itertuples(index=False)):
        img_path = DATA_DIR / row.Path
        img_bgr = cv2.imread(str(img_path))
        if img_bgr is not None:
            img_rgb = cv2.cvtColor(img_bgr, cv2.COLOR_BGR2RGB)
            ax.imshow(img_rgb)
        ax.set_title(
            f"True: {short_label(row.true_label, class_names, 24)}\n"
            f"Pred: {short_label(row.pred_label, class_names, 24)}",
            fontsize=8,
            color="#222222",
        )
        ax.axis("off")

    for ax in axes[len(sample):]:
        ax.axis("off")

    fig.suptitle(f"Sample Misclassified Signs — {model_label}", fontsize=14, fontweight="bold", y=1.01)
    plt.tight_layout()
    plt.savefig(save_path, dpi=300, bbox_inches="tight")
    plt.close()
    print(f"Saved: {save_path}")


# ===========================================================================
# 3. WORST-PERFORMING CLASSES (SINGLE OR SIDE-BY-SIDE)
# ===========================================================================
def class_error_rates(df: pd.DataFrame) -> pd.Series:
    is_err = (df["true_label"] != df["pred_label"]).astype(float)
    return df.assign(err=is_err).groupby("true_label")["err"].mean() * 100.0


def plot_worst_classes_single(
    df: pd.DataFrame,
    class_names: dict[int, str],
    model_label: str,
    save_path: Path,
    top_n: int = 10,
) -> None:
    err_rates = class_error_rates(df).sort_values(ascending=False).head(top_n)
    labels = [short_label(cid, class_names, 26) for cid in err_rates.index]
    values = err_rates.values

    fig, ax = plt.subplots(figsize=(11, 6))
    bars = ax.barh(labels[::-1], values[::-1], color="#337ab7", edgecolor="black", alpha=0.85)
    ax.set_xlabel("Error Rate (%)", fontsize=11)
    ax.set_xlim(0, max(values.max() * 1.15, 1.0))
    ax.set_title(f"Top {top_n} Hardest Classes — {model_label}", fontsize=13, fontweight="bold")
    ax.grid(axis="x", linestyle="--", alpha=0.5)

    for bar in bars:
        width = bar.get_width()
        ax.text(width + max(values.max() * 0.015, 0.2), bar.get_y() + bar.get_height() / 2, f"{width:.1f}%", va="center", fontsize=9)

    plt.tight_layout()
    plt.savefig(save_path, dpi=300, bbox_inches="tight")
    plt.close()
    print(f"Saved: {save_path}")


def plot_worst_classes_comparison(
    df_a: pd.DataFrame,
    df_b: pd.DataFrame,
    label_a: str,
    label_b: str,
    class_names: dict[int, str],
    save_path: Path,
    top_n: int = 10,
) -> None:
    comp = pd.DataFrame({
        label_a: class_error_rates(df_a),
        label_b: class_error_rates(df_b),
    }).fillna(0.0)
    comp["avg_err"] = comp.mean(axis=1)
    worst = comp.sort_values("avg_err", ascending=False).head(top_n)

    labels = [short_label(cid, class_names, 26) for cid in worst.index]
    y = np.arange(len(labels))
    height = 0.38

    fig, ax = plt.subplots(figsize=(11.5, 6))
    ax.barh(y + height / 2, worst[label_a].values[::-1], height, label=label_a, color="#337ab7")
    ax.barh(y - height / 2, worst[label_b].values[::-1], height, label=label_b, color="#f0ad4e")

    ax.set_yticks(y)
    ax.set_yticklabels(labels[::-1], fontsize=9.5)
    ax.set_xlabel("Error Rate (%)", fontsize=11)
    ax.set_title(f"Top {top_n} Hardest Classes — {label_a} vs. {label_b}", fontsize=12.5, fontweight="bold")
    ax.legend(loc="lower right")
    ax.grid(axis="x", linestyle="--", alpha=0.5)

    plt.tight_layout()
    plt.savefig(save_path, dpi=300, bbox_inches="tight")
    plt.close()
    print(f"Saved: {save_path}")


# ===========================================================================
# 4. MODEL DISAGREEMENT BREAKDOWN (TWO-MODEL MODE)
# ===========================================================================
def plot_model_disagreement(
    df_a: pd.DataFrame,
    df_b: pd.DataFrame,
    label_a: str,
    label_b: str,
    save_path: Path,
) -> None:
    merged = pd.merge(
        df_a.rename(columns={"pred_label": "pred_a"}),
        df_b[["Path", "pred_label"]].rename(columns={"pred_label": "pred_b"}),
        on="Path",
    )

    a_ok = merged["true_label"] == merged["pred_a"]
    b_ok = merged["true_label"] == merged["pred_b"]

    both_ok = int((a_ok & b_ok).sum())
    both_wrong = int((~a_ok & ~b_ok).sum())
    only_a_ok = int((a_ok & ~b_ok).sum())
    only_b_ok = int((~a_ok & b_ok).sum())
    total = len(merged)

    print(f"\n--- Agreement Summary: {label_a} vs. {label_b} ---")
    print(f"Total test images:              {total}")
    print(f"Both correct:                   {both_ok} ({both_ok / total:.2%})")
    print(f"Both wrong (shared failures):   {both_wrong} ({both_wrong / total:.2%})")
    print(f"Only {label_a} correct:  {only_a_ok} ({only_a_ok / total:.2%})")
    print(f"Only {label_b} correct:  {only_b_ok} ({only_b_ok / total:.2%})")

    categories = [
        "Both Wrong\n(Shared Failures)",
        f"Only {label_a}\nCorrect",
        f"Only {label_b}\nCorrect",
    ]
    counts = [both_wrong, only_a_ok, only_b_ok]
    colors = ["#d9534f", "#337ab7", "#f0ad4e"]

    fig, ax = plt.subplots(figsize=(9.5, 5.2))
    bars = ax.bar(categories, counts, color=colors, edgecolor="black", alpha=0.85, width=0.52)
    ax.set_ylabel("Number of Test Images", fontsize=11)
    ax.set_ylim(0, max(max(counts) * 1.22, 1))
    ax.set_title(
        f"Error & Disagreement Breakdown (Both Correct: {both_ok}/{total} = {both_ok / total:.2%})",
        fontsize=12,
        fontweight="bold",
        pad=12,
    )
    ax.grid(axis="y", linestyle="--", alpha=0.5)

    for bar, count in zip(bars, counts):
        ax.text(
            bar.get_x() + bar.get_width() / 2,
            bar.get_height() + max(counts) * 0.02,
            f"{count}\n({count / total:.2%})",
            ha="center",
            va="bottom",
            fontsize=10,
            fontweight="bold",
        )

    plt.tight_layout()
    plt.savefig(save_path, dpi=300, bbox_inches="tight")
    plt.close()
    print(f"Saved: {save_path}")


# ===========================================================================
# MAIN CLI ENTRYPOINT
# ===========================================================================
def print_metrics(df: pd.DataFrame, label: str) -> None:
    acc = accuracy_score(df["true_label"], df["pred_label"])
    macro_f1 = f1_score(df["true_label"], df["pred_label"], average="macro")
    n_err = int((df["true_label"] != df["pred_label"]).sum())
    print(f"{label} -> Accuracy: {acc:.4f} | Macro F1: {macro_f1:.4f} | Errors: {n_err}/{len(df)}")


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(description="Generate error-analysis plots from prediction CSVs.")
    parser.add_argument(
        "csv",
        help="Primary prediction CSV filename (inside traditional/outputs/) or path.",
    )
    parser.add_argument(
        "-c", "--compare",
        default=None,
        help="Optional second CSV to compare against (adds comparison & disagreement charts).",
    )
    parser.add_argument(
        "-l", "--label",
        default=None,
        help="Optional custom plot title label for the primary CSV.",
    )
    parser.add_argument(
        "--compare-label",
        default=None,
        help="Optional custom plot title label for the comparison CSV.",
    )
    parser.add_argument(
        "--seed",
        type=int,
        default=42,
        help="Random seed for sampling the visual failure grid (default: 42).",
    )
    return parser.parse_args()


def main() -> None:
    args = parse_args()
    class_names = load_class_names(CLASS_CSV)

    primary_path = resolve_csv_path(args.csv)
    df_primary = pd.read_csv(primary_path)
    label_primary = args.label or format_model_label(primary_path.stem)

    print("\n--- Summary Metrics ---")
    print_metrics(df_primary, label_primary)

    if args.compare:
        compare_path = resolve_csv_path(args.compare)
        df_compare = pd.read_csv(compare_path)
        label_compare = args.compare_label or format_model_label(compare_path.stem)
        print_metrics(df_compare, label_compare)

        run_dir = PLOTS_DIR / f"{primary_path.stem}_vs_{compare_path.stem}"
        run_dir.mkdir(parents=True, exist_ok=True)

        plot_top_confusions(df_primary, class_names, label_primary, run_dir / "top_confusions.png")
        plot_failure_grid(df_primary, class_names, label_primary, run_dir / "failure_grid.png", seed=args.seed)
        plot_worst_classes_comparison(
            df_primary, df_compare, label_primary, label_compare, class_names, run_dir / "worst_classes_comparison.png"
        )
        plot_model_disagreement(
            df_primary, df_compare, label_primary, label_compare, run_dir / "model_disagreement.png"
        )
    else:
        run_dir = PLOTS_DIR / primary_path.stem
        run_dir.mkdir(parents=True, exist_ok=True)

        plot_top_confusions(df_primary, class_names, label_primary, run_dir / "top_confusions.png")
        plot_failure_grid(df_primary, class_names, label_primary, run_dir / "failure_grid.png", seed=args.seed)
        plot_worst_classes_single(df_primary, class_names, label_primary, run_dir / "worst_classes.png")

    print(f"\nAll plots saved to: {run_dir}")


if __name__ == "__main__":
    main()